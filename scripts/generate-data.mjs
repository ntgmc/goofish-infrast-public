import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = resolve(root, 'netlify/functions/efficiency-data.json')
const targetPath = resolve(root, 'netlify/functions/data.ts')
const buildMetaPath = resolve(root, 'src/lib/build-meta.ts')
const packagePath = resolve(root, 'package.json')
const LINE_ENDING = '\r\n'

const source = await readFile(sourcePath, 'utf8')
const data = JSON.parse(source.replace(/^\uFEFF/, ''))
const packageJson = JSON.parse(await readFile(packagePath, 'utf8'))
const sourceHash = createHash('sha256').update(source).digest('hex')
const generatedAt = process.env.GENERATED_AT || new Date().toISOString()
const shortSha = getShortSha()
const baseVersion = String(packageJson.version || '0.0.0')
const buildId = process.env.GITHUB_RUN_NUMBER || process.env.DEPLOY_ID || process.env.BUILD_ID || 'local'
const defaultBuildVersion = shortSha
  ? `${baseVersion}+${buildId}.${shortSha}`
  : `${baseVersion}+${buildId}`
const dataVersion = process.env.DATA_VERSION || `data.${sourceHash.slice(0, 12)}`
const appBuildMeta = {
  frontend_version: process.env.FRONTEND_VERSION || process.env.APP_VERSION || defaultBuildVersion,
  backend_version: process.env.BACKEND_VERSION || process.env.APP_VERSION || defaultBuildVersion,
  data_version: dataVersion,
  generated_at: generatedAt,
  source_summary: buildSourceSummary(data, sourceHash),
  git_sha: process.env.GIT_SHA || process.env.GITHUB_SHA || process.env.COMMIT_REF || null,
  build_context: process.env.BUILD_CONTEXT || process.env.GITHUB_EVENT_NAME || process.env.CONTEXT || 'local',
}
const dataMetadata = {
  data_version: appBuildMeta.data_version,
  generated_at: appBuildMeta.generated_at,
  source_summary: appBuildMeta.source_summary,
}
const output = [
  '// Auto-generated from efficiency-data.json',
  '// Do not edit this file directly. Update efficiency-data.json and run npm run generate:data.',
  `export const EFFICIENCY_DATA_METADATA = ${JSON.stringify(dataMetadata)} as const;`,
  `export const EFFICIENCY_DATA: Record<string, unknown> = ${JSON.stringify(data)};`,
  '',
].join(LINE_ENDING)

await writeFile(targetPath, output, 'utf8')

const buildMetaOutput = [
  '// Auto-generated by scripts/generate-data.mjs',
  '// Do not edit this file directly.',
  `export const APP_BUILD_META = ${JSON.stringify(appBuildMeta, null, 2).replace(/\n/g, LINE_ENDING)} as const;`,
  '',
  'export type AppBuildMeta = typeof APP_BUILD_META;',
  '',
].join(LINE_ENDING)

await writeFile(buildMetaPath, buildMetaOutput, 'utf8')

function getShortSha() {
  const sha = process.env.GIT_SHA || process.env.GITHUB_SHA || process.env.COMMIT_REF
  return sha ? sha.slice(0, 7) : ''
}

function buildSourceSummary(rawData, hash) {
  const workplaces = rawData.workplaces ?? {}
  const tradingRules = rawData.combination_rules?.trading_station ?? {}
  const manufacturingRules = rawData.combination_rules?.manufacturing_station ?? {}
  const controlRules = rawData.control_center_rules ?? []
  const workplaceCount = Object.values(workplaces).reduce((count, value) => {
    if (Array.isArray(value)) return count + value.length
    return count + (value ? 1 : 0)
  }, 0)

  return [
    'source=netlify/functions/efficiency-data.json',
    `sha256=${hash.slice(0, 12)}`,
    `workplaces=${workplaceCount}`,
    `trading_rule_groups=${Object.keys(tradingRules).length}`,
    `manufacturing_rule_groups=${Object.keys(manufacturingRules).length}`,
    `control_center_rules=${Array.isArray(controlRules) ? controlRules.length : 0}`,
  ].join('; ')
}
