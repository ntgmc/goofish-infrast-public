#!/usr/bin/env python3
"""Generate minimal square Xianyu listing covers for points recharge tiers.

The image model only creates a text-free background. Pillow overlays the exact
points amount and bonus label so listing thumbnails never contain AI-mangled
numbers or Chinese text.

The script never stores credentials. Set KRILL_AI_API_KEY in the environment
before running a non-dry command. Existing assets are skipped unless --force is
supplied. Public tiers are generated by default; use --include-test or --only 1
to include the internal 1 yuan test tier.
"""

