OUTPUT_DIR = ROOT / "public" / "assets" / "points-listing-covers"
DEFAULT_BASE_URL = "https://api.krill-ai.net/v1"
DEFAULT_MODEL = "gpt-image-2"
FINAL_SIZE = 1024


@dataclass(frozen=True)
class ListingTier:
    price_yuan: int
    base_points: int
    bonus_points: int
    accent_description: str
    public: bool = True

    @property
    def code(self) -> str:
        return str(self.price_yuan)

    @property
    def total_points(self) -> int:
        return self.base_points + self.bonus_points

    @property
    def filename(self) -> str:
        return f"points-tier-{self.price_yuan}-yuan.png"


