// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { copy } from '../../copy'
import GenerationProgressDemo from './GenerationProgressDemo'

const requests = vi.hoisted(() => ({ session: vi.fn() }))
vi.mock('../../lib/admin-api-client', () => ({ adminApiJson: requests.session, ADMIN_SESSION_EXPIRED_EVENT: 'goofish:admin-session-expired' }))
vi.mock('../../lib/motion-preference', () => ({ useAppReducedMotion: () => true }))
const text = copy.v2.progressDemo
beforeEach(() => {
  vi.useFakeTimers()
  vi.stubGlobal('fetch', vi.fn())
  requests.session.mockReset().mockResolvedValue({ user: { username: 'admin' } })
  localStorage.setItem('demo-workspace-sentinel', 'unchanged')
  sessionStorage.setItem('demo-job-sentinel', 'unchanged')
})
afterEach(() => {
  cleanup()
  expect(fetch).not.toHaveBeenCalled()
  expect(requests.session.mock.calls.every(([url]) => url === '/api/admin/session')).toBe(true)
  expect(localStorage.getItem('demo-workspace-sentinel')).toBe('unchanged')
  expect(sessionStorage.getItem('demo-job-sentinel')).toBe('unchanged')
  localStorage.clear()
  sessionStorage.clear()
  vi.useRealTimers()
  vi.unstubAllGlobals()
})
async function openDemo() {
  render(<GenerationProgressDemo />)
  await act(async () => { await Promise.resolve() })
  fireEvent.click(screen.getByRole('button', { name: text.open }))
}
const card = () => screen.getByRole('region', { name: copy.common.components_ScheduleProgress_001 })
const next = () => fireEvent.click(screen.getByRole('button', { name: text.next }))
const select = (value: string) => fireEvent.change(screen.getByRole('combobox', { name: text.scenario }), { target: { value } })

it.each([{}, { user: null }, { user: { username: 1 } }])('hides the entry without a confirmed administrator session: %j', async (response) => {
  requests.session.mockResolvedValue(response)
  render(<GenerationProgressDemo />)
  expect(screen.queryByRole('button', { name: text.open })).not.toBeInTheDocument()
  await act(async () => { await Promise.resolve() })
  expect(screen.queryByRole('button', { name: text.open })).not.toBeInTheDocument()
})

it('hides failed session checks and removes an open demo when the administrator session expires', async () => {
  requests.session.mockRejectedValue(new Error('Unauthorized'))
  render(<GenerationProgressDemo />)
  await act(async () => { await Promise.resolve() })
  expect(screen.queryByRole('button', { name: text.open })).not.toBeInTheDocument()
  requests.session.mockResolvedValue({ user: { username: 'admin' } })
  await act(async () => { window.dispatchEvent(new Event('focus')) })
  fireEvent.click(screen.getByRole('button', { name: text.open }))
  expect(card()).toHaveAttribute('data-status', 'queued')
  act(() => { window.dispatchEvent(new Event('goofish:admin-session-expired')) })
  await act(async () => vi.advanceTimersByTimeAsync(20_000))
  expect(screen.queryByRole('button', { name: text.open })).not.toBeInTheDocument()
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(vi.getTimerCount()).toBe(0)
})

it('plays the real progress component through completion without submitting a job or changing stored data', async () => {
  await openDemo()
  expect(card()).toHaveAttribute('data-status', 'queued')
  await act(async () => vi.advanceTimersByTimeAsync(1800))
  expect(card()).toHaveAttribute('data-status', 'running')
  expect(screen.getByRole('status')).toHaveTextContent(copy.common.components_ScheduleProgress_113)
  await act(async () => vi.advanceTimersByTimeAsync(4500))
  expect(screen.getByText(copy.common.components_ScheduleProgress_111).closest('li')).toHaveAttribute('aria-current', 'step')
  await act(async () => vi.advanceTimersByTimeAsync(3500))
  expect(card()).toHaveAttribute('data-status', 'finishing')
  await act(async () => vi.advanceTimersByTimeAsync(1600))
  expect(screen.queryByRole('progressbar')).not.toBeInTheDocument()
  expect(screen.getByRole('status')).toHaveTextContent(text.completed)
  expect(screen.getByRole('button', { name: text.next })).toBeDisabled()
})

it('freezes reconnecting and stopped states, resumes, and resets each selected scenario', async () => {
  await openDemo()
  select('reconnect')
  next(); next()
  expect(card().querySelector('.schedule-progress-symbol')).toHaveAttribute('data-state', 'reconnecting')
  const paused = screen.getByRole('progressbar').getAttribute('aria-valuenow')
  await act(async () => vi.advanceTimersByTimeAsync(2000))
  expect(screen.getByRole('progressbar')).toHaveAttribute('aria-valuenow', paused)
  next()
  expect(card().querySelector('.schedule-progress-symbol')).toHaveAttribute('data-state', 'running')
  expect(Number(screen.getByRole('progressbar').getAttribute('aria-valuenow'))).toBeGreaterThanOrEqual(Number(paused))
  select('failed')
  next(); next()
  expect(card()).toHaveAttribute('data-status', 'failed')
  await act(async () => vi.advanceTimersByTimeAsync(10_000))
  expect(card()).toHaveAttribute('data-status', 'failed')
  select('cancelled')
  next(); next()
  expect(card()).toHaveAttribute('data-status', 'cancelling')
  next()
  expect(card()).toHaveAttribute('data-status', 'cancelled')
  fireEvent.click(screen.getByRole('button', { name: text.restart }))
  expect(card()).toHaveAttribute('data-status', 'queued')
})

it('clears playback when closed and starts a fresh demo on reopening', async () => {
  await openDemo()
  fireEvent.click(screen.getByRole('button', { name: copy.v2.close }))
  await act(async () => vi.advanceTimersByTimeAsync(20_000))
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(vi.getTimerCount()).toBe(0)
  fireEvent.click(screen.getByRole('button', { name: text.open }))
  expect(card()).toHaveAttribute('data-status', 'queued')
  select('quick')
  for (let i = 0; i < 3; i++) await act(async () => vi.advanceTimersByTimeAsync(250))
  expect(screen.getByRole('status')).toHaveTextContent(text.completed)
})
